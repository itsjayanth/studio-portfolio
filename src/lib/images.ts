export type ImageCategory = keyof typeof POOLS;

function buildUrl(id: string, { w = 1200, h, q = 75 }: { w?: number; h?: number; q?: number } = {}) {
  const params = new URLSearchParams({ auto: "format", fit: "crop", w: String(w), q: String(q) });
  if (h) params.set("h", String(h));
  return `https://images.unsplash.com/photo-${id}?${params.toString()}`;
}

/** Deterministic, category-scoped Unsplash image URL. */
export function categoryImage(
  category: ImageCategory,
  index: number,
  opts?: { w?: number; h?: number; q?: number },
) {
  const pool = POOLS[category];
  return buildUrl(pool[index % pool.length], opts);
}

/** Square portrait, for testimonials / team avatars. */
export function portraitImage(category: "headshotWoman" | "headshotMan", index: number, size = 200) {
  return categoryImage(category, index, { w: size, h: size, q: 80 });
}
